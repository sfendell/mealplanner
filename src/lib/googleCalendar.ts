import { clearStoredAccessToken } from "./googleAuth";

export type CalendarMealEvent = {
  title: string;
  date: Date;
  attendees: string[];
  description?: string;
  timezone: string;
};

export type ShoppingListItem = {
  ingredient: string;
  quantity: number | null;
  isBoolean: boolean;
};

async function insertEvent(
  accessToken: string,
  body: Record<string, unknown>
): Promise<{ id: string; summary: string; htmlLink?: string; date?: string }> {
  const response = await fetch(
    "https://www.googleapis.com/calendar/v3/calendars/primary/events?sendUpdates=all",
    {
      method: "POST",
      headers: {
        Authorization: `Bearer ${accessToken}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify(body),
    }
  );

  if (response.status === 401) {
    clearStoredAccessToken();
    throw new Error("Google session expired. Sign in again and retry.");
  }

  if (!response.ok) {
    const details = await response.text();
    throw new Error(`Calendar API error (${response.status}): ${details}`);
  }

  const data = await response.json();
  return {
    id: data.id,
    summary: data.summary,
    htmlLink: data.htmlLink,
    date: data.start?.dateTime || data.start?.date,
  };
}

function toDateString(date: Date, timezone: string): string {
  return date.toLocaleDateString("en-CA", { timeZone: timezone });
}

export async function createMealPrepCalendarEvents(options: {
  accessToken: string;
  events: CalendarMealEvent[];
  shoppingList: Record<string, ShoppingListItem>;
  veggieCount: number;
  planType: string;
  startDay: string;
  endDay: string;
}): Promise<
  Array<{ id: string; title: string; date?: string; htmlLink?: string }>
> {
  const {
    accessToken,
    events,
    shoppingList,
    veggieCount,
    planType,
    startDay,
    endDay,
  } = options;

  const created: Array<{
    id: string;
    title: string;
    date?: string;
    htmlLink?: string;
  }> = [];

  if (Object.keys(shoppingList).length > 0 && events.length > 0) {
    const firstEventDate = new Date(events[0].date);
    const shoppingListDate = new Date(firstEventDate);
    shoppingListDate.setDate(firstEventDate.getDate() - 1);

    const shoppingItems = Object.values(shoppingList).sort((a, b) => {
      if (a.isBoolean && !b.isBoolean) return 1;
      if (!a.isBoolean && b.isBoolean) return -1;
      return a.ingredient.localeCompare(b.ingredient);
    });

    const shoppingListDescription = `
Shopping List for ${planType} (${startDay}${endDay ? ` to ${endDay}` : ""})

Ingredients:
${shoppingItems
  .map((item) => {
    if (item.isBoolean) {
      return `• ${item.ingredient}`;
    }
    return `• ${item.quantity ? `${item.quantity} ` : ""}${item.ingredient}`;
  })
  .join("\n")}

${veggieCount > 0 ? `Total Veggie Sides Needed: ${veggieCount}` : ""}

Generated by MealPrep App
    `.trim();

    const timezone = events[0].timezone;
    const userDateString = toDateString(shoppingListDate, timezone);

    const shoppingResponse = await insertEvent(accessToken, {
      summary: "🛒 Shopping List - MealPrep",
      description: shoppingListDescription,
      start: { date: userDateString },
      end: { date: userDateString },
      attendees: events[0].attendees.map((email) => ({ email })),
      reminders: {
        useDefault: false,
        overrides: [
          { method: "email", minutes: 24 * 60 },
          { method: "popup", minutes: 60 },
        ],
      },
    });

    created.push({
      id: shoppingResponse.id,
      title: shoppingResponse.summary,
      date: shoppingResponse.date,
      htmlLink: shoppingResponse.htmlLink,
    });
  }

  for (const event of events) {
    const userDateString = toDateString(event.date, event.timezone);
    const response = await insertEvent(accessToken, {
      summary: event.title,
      description: event.description || "",
      start: {
        dateTime: `${userDateString}T18:00:00`,
        timeZone: event.timezone,
      },
      end: {
        dateTime: `${userDateString}T19:00:00`,
        timeZone: event.timezone,
      },
      attendees: event.attendees.map((email) => ({ email })),
      reminders: {
        useDefault: false,
        overrides: [
          { method: "email", minutes: 24 * 60 },
          { method: "popup", minutes: 30 },
        ],
      },
    });

    created.push({
      id: response.id,
      title: response.summary,
      date: response.date,
      htmlLink: response.htmlLink,
    });
  }

  return created;
}
